package org.lolaf.staffix.stores.sessions.jdbc;

import lombok.Builder;
import lombok.Getter;
import lombok.Singular;
import org.jspecify.annotations.NullMarked;
import org.jspecify.annotations.Nullable;
import org.lolaf.staffix.api.session.ConfigValueResolver;
import org.lolaf.staffix.api.session.FixSessionsSettingsStoreSettings;

import javax.sql.DataSource;
import java.util.List;

/**
 * The data source and table prefix the JDBC session settings store uses. The table itself is generated by the DDL
 * plugin.
 */
@NullMarked
@Getter
@Builder(toBuilder = true)
public class JdbcSessionsSettingsStoreSettings implements FixSessionsSettingsStoreSettings {

    /**
     * Names this instance, so a session can select it by id when more than one is configured.
     */
    @Builder.Default
    private final String instanceId = DEFAULT_INSTANCE_ID;

    /**
     * Where the {@code fix_sessions_settings} table lives; pooled, since every change is one statement on its own
     * connection.
     */
    private final DataSource dataSource;

    /**
     * Table name prefix, letters, digits and underscores only; the table is then {@code <prefix>_fix_sessions_settings}.
     */
    @Builder.Default
    private final String tablePrefix = "";

    /**
     * Used for the rows' {@code engine_id} instead of the engine's instance id, so the two nodes of a high availability
     * pair read the same rows while keeping their own ids. The same value on both, the pair's name for example; never on
     * unrelated engines, which would then share their sessions.
     */
    private final @Nullable String engineIdOverride;

    /**
     * Resolvers for the {@code ${...}} placeholders in a row, asked in the order given. Empty falls back to system
     * properties then environment variables.
     */
    @Singular
    private final List<ConfigValueResolver> configValueResolvers;
}
